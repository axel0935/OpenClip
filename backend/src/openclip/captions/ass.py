"""ASS subtitle generation for one clip.

Design notes
------------
* **Sizing.** ``CaptionStyle.font_size`` is an em size in canvas pixels.
  libass instead fits the font's ``usWinAscent + usWinDescent`` box to
  ``Fontsize``, so the emitted value is ``font_size * window_ratio`` (see
  :mod:`openclip.captions.ttf`). Without this, text renders 18-45 % small and
  every plate lands in the wrong place.
* **Positioning.** Each event is placed explicitly: ``\\an5`` + ``\\pos`` for
  text, ``\\an7`` + ``\\pos`` with a local-space vector path for plates. Nothing
  relies on libass' own wrapping, so line breaks, measured word boxes and plates
  always agree.
* **Animation.** ``pop``/``fade``/``slide_up``/``bounce`` run once per chunk, on
  its first event. Restarting a fade or a scale on every word slice makes text
  flicker and drift, which is exactly what short-form captions must not do.
* **Determinism.** Same inputs produce the same bytes.
"""

import logging
import math

from openclip.captions.chunks import CaptionChunk, build_chunks, case_text, clip_words
from openclip.captions.color import color_tags
from openclip.captions.text import (
    CANVAS_HEIGHT,
    CANVAS_WIDTH,
    BlockLayout,
    ass_fontsize,
    font_metrics,
)
from openclip.captions.timecode import ass_time, to_centiseconds
from openclip.core.models import CaptionStyle, Clip, Transcript

LOGGER = logging.getLogger(__name__)

#: Layer for the whole-chunk background plate.
BACKGROUND_LAYER = 0
#: Layer for the blurred copy of the text that fakes a soft drop shadow.
GLOW_LAYER = 1
#: Layer for the active-word plate in ``word_box`` mode.
WORD_BOX_LAYER = 2
#: Layer for the words themselves.
TEXT_LAYER = 3

#: Horizontal margins written in the style line, in canvas pixels.
MARGIN_LR = 60
#: Corner radius and padding of an active-word plate, in em fractions.
BOX_RADIUS_EM = 0.18
BOX_PAD_X_EM = 0.16
BOX_PAD_Y_EM = 0.06
#: Line segments used to approximate one rounded corner.
CORNER_STEPS = 6

_ALIGNMENT = {"bottom": 2, "middle": 5, "top": 8}

#: 80 % -> 112 % -> 100 % in 160 ms.
POP_TAGS = r"\fscx80\fscy80\t(0,80,\fscx112\fscy112)\t(80,160,\fscx100\fscy100)"
#: Two decaying overshoots in 290 ms.
BOUNCE_TAGS = (
    r"\fscx84\fscy84\t(0,70,\fscx114\fscy114)\t(70,150,\fscx95\fscy95)"
    r"\t(150,220,\fscx105\fscy105)\t(220,290,\fscx100\fscy100)"
)
FADE_TAGS = r"\fad(120,80)"
SLIDE_MS = 220
SLIDE_PIXELS = 40

_STYLE_FORMAT = (
    "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, "
    "BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, "
    "BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding"
)

_HEADER = f"""[Script Info]
; Generated by OpenClip
ScriptType: v4.00+
PlayResX: {{width}}
PlayResY: {{height}}
ScaledBorderAndShadow: yes
WrapStyle: 2

[V4+ Styles]
{_STYLE_FORMAT}
{{style_line}}

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""


class Event:
    """One ASS dialogue line."""

    __slots__ = ("end_cs", "layer", "start_cs", "text")

    def __init__(self, layer: int, start_cs: int, end_cs: int, text: str) -> None:
        self.layer = layer
        self.start_cs = start_cs
        self.end_cs = end_cs
        self.text = text

    def render(self) -> str:
        """Serialise the event as a ``Dialogue:`` line."""
        return (
            f"Dialogue: {self.layer},{ass_time(self.start_cs)},{ass_time(self.end_cs)},"
            f"Default,,0,0,0,,{self.text}"
        )


def _fmt(value: float) -> str:
    """Format a float compactly and deterministically for ASS tags."""
    return f"{value:.2f}".rstrip("0").rstrip(".") if value != int(value) else str(int(value))


def _style_line(style: CaptionStyle) -> str:
    """Build the single ``Style:`` line for a preset.

    Karaoke needs ASS' own fill animation: unfilled glyphs use
    ``SecondaryColour`` and ``\\kf`` sweeps them into ``PrimaryColour``. Every
    other mode uses the plain text colour as primary and keeps the highlight
    colour for override tags.
    """
    if style.highlight_mode == "karaoke_fill":
        primary = style.highlight_color
        secondary = style.text_color
    else:
        primary = style.text_color
        secondary = style.highlight_color
    back = style.shadow_color if style.shadow_color is not None else "#00000000"
    # The soft shadow is drawn by a separate blurred layer (see ``_glow_event``):
    # libass' built-in Shadow is a hard offset copy, which doubles the glyphs.
    shadow = "0"
    fields = [
        "Default",
        style.font_family,
        _fmt(ass_fontsize(style)),
        _ass_style_color(primary),
        _ass_style_color(secondary),
        _ass_style_color(style.outline_color),
        _ass_style_color(back),
        "-1" if style.bold else "0",
        "-1" if style.italic else "0",
        "0",
        "0",
        "100",
        "100",
        _fmt(style.letter_spacing),
        "0",
        "1",
        _fmt(style.outline_width),
        shadow,
        str(_ALIGNMENT[style.position]),
        str(MARGIN_LR),
        str(MARGIN_LR),
        str(style.margin_v),
        "1",
    ]
    return "Style: " + ",".join(fields)


def _ass_style_color(value: str) -> str:
    """Return the ``&HAABBGGRR`` style-line colour for a hex colour."""
    from openclip.captions.color import ass_color

    return ass_color(value)


def _block_top(style: CaptionStyle, block: BlockLayout) -> float:
    """Return the top edge of a caption block in canvas pixels."""
    if style.position == "top":
        return float(style.margin_v)
    if style.position == "middle":
        return (CANVAS_HEIGHT - block.height) / 2
    return CANVAS_HEIGHT - style.margin_v - block.height


def _entry_tags(style: CaptionStyle, center_y: float) -> str:
    """Return the once-per-chunk entry animation tags."""
    if style.animation == "fade":
        return FADE_TAGS
    if style.animation == "slide_up":
        start_y = round(center_y + SLIDE_PIXELS)
        return (
            f"\\move({CANVAS_WIDTH // 2},{start_y},{CANVAS_WIDTH // 2},{round(center_y)},"
            f"0,{SLIDE_MS})\\alpha&HFF&\\t(0,{SLIDE_MS},\\alpha&H00&)"
        )
    if style.animation == "pop":
        return POP_TAGS
    if style.animation == "bounce":
        return BOUNCE_TAGS
    return ""


def _rounded_rect(width: float, height: float, radius: float) -> str:
    """Return a local-space ASS drawing path for a rounded rectangle.

    The path spans ``[0, width] x [0, height]`` so that ``\\an7\\pos(x, y)``
    places the rectangle's top-left corner exactly at ``(x, y)``.
    """
    w = max(1.0, width)
    h = max(1.0, height)
    r = max(0.0, min(radius, w / 2, h / 2))
    parts = [f"m {r:.1f} 0", f"l {w - r:.1f} 0"]
    parts.extend(_corner(w - r, r, r, -90.0, 0.0))
    parts.append(f"l {w:.1f} {h - r:.1f}")
    parts.extend(_corner(w - r, h - r, r, 0.0, 90.0))
    parts.append(f"l {r:.1f} {h:.1f}")
    parts.extend(_corner(r, h - r, r, 90.0, 180.0))
    parts.append(f"l 0 {r:.1f}")
    parts.extend(_corner(r, r, r, 180.0, 270.0))
    return " ".join(parts)


def _corner(cx: float, cy: float, radius: float, start_deg: float, end_deg: float) -> list[str]:
    """Approximate one corner arc with short line segments."""
    parts: list[str] = []
    for step in range(1, CORNER_STEPS + 1):
        angle = math.radians(start_deg + (end_deg - start_deg) * step / CORNER_STEPS)
        parts.append(f"l {cx + radius * math.cos(angle):.1f} {cy + radius * math.sin(angle):.1f}")
    return parts


def _plate(
    layer: int,
    start_cs: int,
    end_cs: int,
    left: float,
    top: float,
    width: float,
    height: float,
    radius: float,
    color: str,
) -> Event:
    """Build a filled rounded rectangle event."""
    body = (
        f"{{\\an7\\pos({left:.1f},{top:.1f})\\p1\\bord0\\shad0"
        f"{color_tags(color)}}}"
        f"{_rounded_rect(width, height, radius)}"
    )
    return Event(layer=layer, start_cs=start_cs, end_cs=end_cs, text=body)


def _line_index_of_word(chunk: CaptionChunk) -> list[int]:
    """Return the line index of every word in a chunk, in reading order."""
    indices: list[int] = []
    for line_index, line in enumerate(chunk.block.lines):
        indices.extend([line_index] * len(line.word_boxes))
    return indices


def _chunk_text(
    chunk: CaptionChunk,
    style: CaptionStyle,
    center_y: float,
    active: int | None,
    entry_tags: str,
) -> str:
    """Render a chunk's text, highlighting one word when requested."""
    tags = f"\\an5\\pos({CANVAS_WIDTH // 2},{round(center_y)}){entry_tags}"
    pieces = [f"{{{tags}}}"]
    line_of_word = _line_index_of_word(chunk)
    plate_mode = style.highlight_mode == "word_box"
    for index, word in enumerate(chunk.words):
        if index > 0:
            pieces.append("\\N" if line_of_word[index] != line_of_word[index - 1] else " ")
        if active == index and not plate_mode:
            pieces.append(f"{{{color_tags(style.highlight_color)}}}")
            pieces.append(case_text(word.text, style))
            pieces.append(f"{{{color_tags(style.text_color)}}}")
        else:
            pieces.append(case_text(word.text, style))
    return "".join(pieces)


def _glow_event(
    chunk: CaptionChunk,
    style: CaptionStyle,
    start_cs: int,
    end_cs: int,
    center_y: float,
    entry_tags: str = "",
) -> Event | None:
    """Build a blurred copy of the chunk behind it, when the style asks for a glow.

    libass draws ``Shadow`` as a hard, offset copy of the outlined glyphs. Over
    large display type that reads as doubled, italic-looking text rather than the
    soft glow these presets describe ("magenta glow", "deep soft shadow"). A
    blurred copy on a lower layer reproduces the intended look using only the
    fields ``CaptionStyle`` already defines.

    ``entry_tags`` must match the text layer's entry animation, otherwise the
    shadow stays at rest size while the words pop, and the two separate visibly.

    Returns ``None`` for styles without a shadow colour and non-zero offset.
    """
    if style.shadow_color is None or style.shadow_offset <= 0:
        return None
    blur = max(0.6, style.shadow_offset * 0.75)
    offset = style.shadow_offset * 0.6
    tags = (
        f"\\an5\\pos({CANVAS_WIDTH // 2},{round(center_y + offset)})"
        f"{color_tags(style.shadow_color)}\\blur{blur:g}{entry_tags}"
    )
    pieces = [f"{{{tags}}}"]
    line_of_word = _line_index_of_word(chunk)
    for index, word in enumerate(chunk.words):
        if index > 0:
            pieces.append("\\N" if line_of_word[index] != line_of_word[index - 1] else " ")
        pieces.append(case_text(word.text, style))
    return Event(layer=GLOW_LAYER, start_cs=start_cs, end_cs=end_cs, text="".join(pieces))


def _word_plate(
    chunk: CaptionChunk,
    style: CaptionStyle,
    index: int,
    start_cs: int,
    end_cs: int,
    block_top: float,
) -> Event:
    """Build the rounded plate behind one active word."""
    box = chunk.word_boxes[index]
    em = float(style.font_size)
    radius = em * BOX_RADIUS_EM
    if style.background is not None:
        radius = float(style.background.radius)
    pad_x = em * BOX_PAD_X_EM
    pad_y = em * BOX_PAD_Y_EM
    return _plate(
        layer=WORD_BOX_LAYER,
        start_cs=start_cs,
        end_cs=end_cs,
        left=box.left - pad_x,
        top=block_top + box.top + pad_y * 0.5,
        width=box.width + pad_x * 2,
        height=box.height - pad_y,
        radius=radius,
        color=style.highlight_color,
    )


def _background_plate(
    chunk: CaptionChunk, style: CaptionStyle, start_cs: int, end_cs: int, block_top: float
) -> Event | None:
    """Build the plate behind a whole chunk, if the style defines one."""
    if style.background is None:
        return None
    pad = float(style.background.padding)
    return _plate(
        layer=BACKGROUND_LAYER,
        start_cs=start_cs,
        end_cs=end_cs,
        left=(CANVAS_WIDTH - chunk.block.width) / 2 - pad,
        top=block_top - pad * 0.6,
        width=chunk.block.width + pad * 2,
        height=chunk.block.height + pad * 1.2,
        radius=float(style.background.radius),
        color=style.background.color,
    )


def _slice_bounds(chunk: CaptionChunk, clip_duration: float) -> list[int]:
    """Return strictly increasing centisecond boundaries for the word slices."""
    start_cs = to_centiseconds(chunk.start)
    end_cs = max(start_cs + 1, to_centiseconds(min(chunk.end, clip_duration)))
    if len(chunk.words) == 1:
        return [start_cs, end_cs]
    boundaries = [start_cs]
    for word in chunk.words[1:]:
        value = to_centiseconds(min(word.start, chunk.end))
        boundaries.append(max(boundaries[-1] + 1, min(value, end_cs - 1)))
    boundaries.append(end_cs)
    return boundaries


def _karaoke_segments(chunk: CaptionChunk, start_cs: int, end_cs: int) -> list[tuple[str, int]]:
    """Split a chunk into ``(word, centiseconds)`` segments summing to the event length."""
    total = max(1, end_cs - start_cs)
    raw: list[tuple[str, int]] = []
    cursor = start_cs
    for word in chunk.words:
        word_start = max(cursor, to_centiseconds(word.start))
        word_end = max(word_start + 1, to_centiseconds(word.end))
        if word_start > cursor:
            raw.append(("", word_start - cursor))
        raw.append((word.text, word_end - word_start))
        cursor = word_end
    used = sum(duration for _, duration in raw)
    if used < total:
        raw.append(("", total - used))
    elif used > total:
        raw[-1] = (raw[-1][0], raw[-1][1] - (used - total))
    return [(text, duration) for text, duration in raw if duration > 0]


def _karaoke_text(
    chunk: CaptionChunk, style: CaptionStyle, center_y: float, segments: list[tuple[str, int]]
) -> str:
    """Build the single ``\\kf`` karaoke event for a chunk."""
    tags = f"\\an5\\pos({CANVAS_WIDTH // 2},{round(center_y)}){_entry_tags(style, center_y)}"
    pieces = [f"{{{tags}}}"]
    line_of_word = _line_index_of_word(chunk)
    word_index = 0
    for text, duration_cs in segments:
        pieces.append(f"{{\\kf{duration_cs}}}")
        if not text:
            continue
        if word_index > 0:
            is_line_start = line_of_word[word_index] != line_of_word[word_index - 1]
            pieces.append("\\N" if is_line_start else " ")
        pieces.append(case_text(text, style))
        word_index += 1
    return "".join(pieces)


def _events_for_chunk(
    chunk: CaptionChunk, style: CaptionStyle, clip_duration: float
) -> list[Event]:
    """Build every event for one chunk according to the highlight mode."""
    block_top = _block_top(style, chunk.block)
    center_y = block_top + chunk.block.height / 2
    bounds = _slice_bounds(chunk, clip_duration)
    first_cs, last_cs = bounds[0], bounds[-1]
    events: list[Event] = []
    plate = _background_plate(chunk, style, first_cs, last_cs, block_top)
    if plate is not None:
        events.append(plate)
    entry = _entry_tags(style, center_y)

    def add_glow(start: int, end: int, tags: str) -> None:
        """Append a glow slice matching one text slice, entry animation included."""
        glow = _glow_event(chunk, style, start, end, center_y, tags)
        if glow is not None:
            events.append(glow)

    if style.highlight_mode == "karaoke_fill":
        add_glow(first_cs, last_cs, entry)
        segments = _karaoke_segments(chunk, first_cs, last_cs)
        events.append(
            Event(
                layer=TEXT_LAYER,
                start_cs=first_cs,
                end_cs=last_cs,
                text=_karaoke_text(chunk, style, center_y, segments),
            )
        )
        return events

    if style.highlight_mode == "none" or len(chunk.words) == 1:
        add_glow(first_cs, last_cs, entry)
        events.append(
            Event(
                layer=TEXT_LAYER,
                start_cs=first_cs,
                end_cs=last_cs,
                text=_chunk_text(chunk, style, center_y, None, entry),
            )
        )
        return events

    for index in range(len(chunk.words)):
        slice_start, slice_end = bounds[index], bounds[index + 1]
        slice_entry = entry if index == 0 else ""
        # One glow per text slice, sharing its entry animation: a single glow
        # spanning the chunk would sit at rest size while the text pops.
        add_glow(slice_start, slice_end, slice_entry)
        if style.highlight_mode == "word_box":
            events.append(_word_plate(chunk, style, index, slice_start, slice_end, block_top))
        events.append(
            Event(
                layer=TEXT_LAYER,
                start_cs=slice_start,
                end_cs=slice_end,
                text=_chunk_text(chunk, style, center_y, index, slice_entry),
            )
        )
    return events


def build_ass(transcript: Transcript, clip: Clip, style: CaptionStyle) -> str:
    """Build a complete ASS document for ``clip`` using ``style``.

    Words outside the clip are ignored, timings are clip-relative and every
    event is clamped to the clip duration. The result is deterministic.
    """
    clip_duration = max(0.0, clip.end - clip.start)
    words = clip_words(transcript, clip)
    chunks = build_chunks(words, style, clip_duration)
    events: list[Event] = []
    for chunk in chunks:
        events.extend(_events_for_chunk(chunk, style, clip_duration))
    events.sort(key=lambda event: (event.start_cs, event.layer, event.end_cs))
    lines = [
        _HEADER.format(width=CANVAS_WIDTH, height=CANVAS_HEIGHT, style_line=_style_line(style))
    ]
    written = 0
    for event in events:
        if event.end_cs <= event.start_cs:
            continue
        lines.append(event.render())
        written += 1
    LOGGER.debug("Built ASS for clip %s: %d events", clip.id, written)
    return "\n".join(lines) + "\n"


def caption_metrics(style: CaptionStyle) -> dict[str, float]:
    """Expose resolved sizing for diagnostics and tests."""
    metrics = font_metrics(style)
    return {
        "em_size": metrics.em_size,
        "window_ratio": metrics.window_ratio,
        "ass_fontsize": metrics.ass_fontsize,
        "line_advance": metrics.line_advance,
    }
